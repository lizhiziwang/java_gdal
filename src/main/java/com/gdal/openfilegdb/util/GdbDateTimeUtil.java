package com.gdal.openfilegdb.util;

import java.time.Instant;
import java.time.LocalDateTime;
import java.time.ZoneOffset;

/**
 * FileGDB 日期时间转换。
 *
 * <p>FileGDB 的 {@code FGFT_DATETIME} 用一个 {@code double} 表示
 * <b>自 1899-12-30 00:00:00 UTC 起的天数</b>(这是 Excel/OLE Automation 的
 * 日期基准,ArcGIS 沿用了它),小数部分即当日时间。空值用 {@code NaN} 表示。
 *
 * <p>对标 GDAL {@code filegdbtable.cpp} 里对 {@code FGFT_DATETIME} 的读取:
 * 它把 double 直接塞进 {@code OGRField.Date},由 OGR 的
 * {@code OGRParseDate} 家族负责与 {@code OGRField} 的
 * {@code Year/Month/Day/Hour/Minute/Second} 结构互转。
 */
public final class GdbDateTimeUtil {

    /** 1899-12-30 00:00:00 UTC 对应的 Unix 时间戳(秒)。 */
    public static final double DATETIME_EPOCH_UNIX = -2209161600.0;

    /** 一天的秒数。 */
    public static final double SECONDS_PER_DAY = 86400.0;

    /**
     * "小数部分逼近整秒"的吸附阈值,对应 GDAL 里的 {@code 1e-4}。
     *
     * <p>见 {@code filegdbtable.cpp:1873}:{@code else if (fmod(dfSeconds, 1.0)
     * > 1 - 1e-4)}。
     */
    private static final double DATE_SNAP_EPSILON = 1e-4;

    /**
     * ESRI SDK 写出的 quiet NaN 的位模式。
     *
     * <p><b>它不是</b> IEEE 的规范 quiet NaN:Java 的
     * {@code Double.NaN} 位模式是 {@code 0x7FF8000000000000},而 ESRI SDK
     * 写的是 <b>最低有效位为 1</b> 的 {@code 0x7FF8000000000001}。
     *
     * <p>GDAL 为此专门定义了 {@code getESRI_NAN()}(见
     * {@code filegdbtable.cpp::getESRI_NAN}),注释原文是
     * "Use exact same quiet NaN value as generated by the ESRI SDK, just for
     * the purpose of ensuring binary identical output" —— 本工程照抄,
     * 以保证新建的 .gdb 与 ArcGIS 逐字节一致。
     */
    public static final long ESRI_NAN_BITS = 0x7FF8000000000001L;

    /** {@link #ESRI_NAN_BITS} 对应的 double 值。 */
    public static final double ESRI_NAN = Double.longBitsToDouble(ESRI_NAN_BITS);

    private GdbDateTimeUtil() {
    }

    /**
     * FileGDB 天数 → {@link LocalDateTime}(UTC)。
     *
     * <p>对应 GDAL {@code FileGDBDoubleDateToOGRDate()}
     * ({@code filegdbtable.cpp:1855}),含其中那条**关键的高精度吸附规则**:
     * <pre>
     *   double dfSeconds = (dfVal - 25569.0) * 3600.0 * 24.0;
     *   if (!bHighPrecision)
     *       dfSeconds = std::floor(dfSeconds + 0.5);
     *   else if (fmod(dfSeconds, 1.0) &gt; 1 - 1e-4)
     *       dfSeconds = std::floor(dfSeconds + 0.5);
     * </pre>
     *
     * <p><b>为什么必须吸附:</b>天数存成 {@code double},而 {@code (days * 86400)}
     * 这一步在秒级值上会引入相对误差 {@code ~1e-16 / (days*86400)}。以
     * {@code 2024-03-08 10:30:15} 为例,写出去再读回来会变成
     * {@code 14.999999523} 秒 —— 差那么一点点就掉到下一整秒的下方。GDAL 的
     * 处理是"小数部分离 1 秒不到 1e-4 就直接吸附到整秒",本方法照抄。
     *
     * @param days 自 1899-12-30 UTC 起的天数;NaN 表示空值
     * @return 日期时间;输入为 NaN 时返回 {@code null}
     */
    public static LocalDateTime daysToDateTime(double days) {
        if (Double.isNaN(days)) {
            return null;
        }
        double unix = DATETIME_EPOCH_UNIX + days * SECONDS_PER_DAY;
        // GDAL 的高精度分支:小数部分逼近 1 秒时吸附到整秒(见方法注释)
        double frac = unix - Math.floor(unix);
        if (frac > 1 - DATE_SNAP_EPSILON) {
            unix = Math.floor(unix + 0.5);
        }
        long secs = (long) Math.floor(unix);
        long nanos = Math.round((unix - secs) * 1_000_000_000.0);
        // 四舍五入可能把纳秒推到 1e9,归一化
        if (nanos >= 1_000_000_000L) {
            secs += 1;
            nanos -= 1_000_000_000L;
        }
        if (nanos < 0) {
            secs -= 1;
            nanos += 1_000_000_000L;
        }
        return LocalDateTime.ofInstant(Instant.ofEpochSecond(secs, nanos), ZoneOffset.UTC);
    }

    /**
     * {@link LocalDateTime} → FileGDB 天数。
     *
     * @param dt 日期时间,按 UTC 解释
     * @return 自 1899-12-30 起的天数
     */
    public static double dateTimeToDays(LocalDateTime dt) {
        long secs = dt.toEpochSecond(ZoneOffset.UTC);
        long nanos = dt.getNano();
        double unix = secs + nanos / 1_000_000_000.0;
        return (unix - DATETIME_EPOCH_UNIX) / SECONDS_PER_DAY;
    }

    /**
     * 是否为本工程认定的"空日期"。
     *
     * @param days 天数
     * @return NaN(含 ESRI NaN)时返回 true
     */
    public static boolean isNullDate(double days) {
        return Double.isNaN(days);
    }
}
